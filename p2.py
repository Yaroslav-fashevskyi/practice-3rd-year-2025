# Введення двох цілих чисел
a = int(input("Введіть перше ціле число: "))
b = int(input("Введіть друге ціле число: "))


# Обчислення суми
suma = a + b


# Обчислення частки націло
if b != 0:
   chastka = a // b
   print(f"Сума: {suma}")
   print(f"Частка націло: {chastka}")
else:
   print(f"Сума: {suma}")
   print("Частка націло: неможливо поділити на нуль")